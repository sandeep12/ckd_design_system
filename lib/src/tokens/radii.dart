/// Corner radius tokens (`radius/*`), in logical pixels.
abstract final class DsRadii {
  /// `radius/control-sm` — checkbox box.
  static const double controlSm = 6;

  /// `radius/control` — chips, small surfaces.
  static const double control = 8;

  /// `input/radius`
  static const double input = 8;

  /// `button/radius`
  static const double button = 8;

  /// `radius/surface` — banners, inline surfaces.
  static const double surface = 12;

  /// `radius/overlay` — auth card, modals.
  static const double overlay = 16;

  /// `radius/pill`
  static const double pill = 9999;
}
