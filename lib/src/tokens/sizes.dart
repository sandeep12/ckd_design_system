/// Size tokens (`size/*`, `input/*`, `button/*`), in logical pixels.
abstract final class DsSizes {
  /// `size/icon/sm`
  static const double iconSm = 16;

  /// `size/icon/md`
  static const double iconMd = 20;

  /// `size/icon/lg` — mobile checkbox box.
  static const double iconLg = 24;

  /// `input/height` — web input control height.
  static const double inputHeight = 40;

  /// `size/control/lg` — 48dp touch minimum; mobile input/control height.
  static const double controlLg = 48;

  /// `button/height-lg`
  static const double buttonHeightLg = 48;

  /// `button/pad-x-lg`
  static const double buttonPadXLg = 24;

  /// `button/gap`
  static const double buttonGap = 8;

  /// `input/pad-x`
  static const double inputPadX = 12;

  /// `input/gap-label`
  static const double inputGapLabel = 4;

  /// `border/width/default`
  static const double borderWidthDefault = 1;
}
